//! 2025–2026 expansions M2-W4a cards (exp_tlc_w4a) — the Un'Goro main-set
//! wave, first split: the 96 non-legendary collectible TLC_* cards not
//! landed in W1–W3, plus their handwritten tokens.
//!
//! The wave rule (fidelity-debt §17): "TLC_* collectible cards with rarity
//! != LEGENDARY minus ids landed in W1–W3". The rule yields 97; TLC_249
//! Sizzling Cinder is already written in W3 (exp_tlc_w3.rs — Slagclaw's
//! summon token), so 96 new cards land here.
//!
//! Effect shapes per the D2 random simplification (fidelity-debt §17):
//! - Discover cards (the D2 shape): the six Map cards (TLC_435/442/464/
//!   515/824/900) share one shape — discover from a filtered pool, and if
//!   the discovered card is played this turn, one random unpicked option
//!   is added to the hand (the `Player::map_pending` chain). Other
//!   discovers (TLC_334/434/461/449/109/514) surface the three-option
//!   choice too.
//! - Cursed Catacombs (TLC_451) discovers from the OWN deck and marks the
//!   pick Temporary; Eyes in the Sky (TLC_521) peeks the enemy deck top 3
//!   and moves the pick on top.
//! - Temporary creators reuse the W2 `set_temporary` primitive: Bloodpetal
//!   Biome (TLC_449, the discovered card is Temporary), Cursed Catacombs
//!   (TLC_451), Tunnel Terror (TLC_469 — two random 2-Cost minions),
//!   Spelunker (TLC_450 — next Temporary costs (2) less, one-time).
//! - Small new effects: Mechanized Magma (Fire spell → stats equal to its
//!   Cost), Gorishi Stinger's damage+summon, Storm the Gates' sidequest
//!   reward (a random Beast, cost (3) less), Deathrot Maw's random Fel
//!   Beast, plus the drain, cost-health, Summoned-When-Drawn (via the W3
//!   ninja) and summon-when-drawn chains.
//!
//! Card data: `cards/data/THE_LOST_CITY.json` + the full dump
//! (`/tmp/hs_full.json`, verified 2026-08-09). Tokens absent from the dump
//! (TLC_234t2 Eternal Bloodpetal, TLC_245t Plant, TLC_252t Bones,
//! TLC_427t Rock, TLC_466t Imp, TLC_826t Raptor) are handwritten per the
//! card texts they serve.

