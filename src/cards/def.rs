//! 卡牌定义 — 数据驱动的卡牌数据。
//!
//! 包含怀旧系列（Classic/Basic）卡牌。
//! 跳过会引入跨系列随机卡牌的牌（发现、随机获取、复制对手牌等）。

#![allow(missing_docs)]

use crate::core::component::{AuraEffect, AuraTarget, CardType, SecretTrigger};
use crate::core::effect::{CardEffect, EffectTarget};

/// 卡牌静态定义 — 描述一张卡牌的基本属性和效果。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CardDef {
    pub id: &'static str,
    pub name: &'static str,
    pub card_type: CardType,
    pub cost: i32,
    pub attack: i32,
    pub health: i32,
    pub durability: i32,
    pub battlecry: Option<CardEffect>,
    pub deathrattle: Option<CardEffect>,
    pub taunt: bool,
    pub hero_power: Option<CardEffect>,
    pub aura: Option<(AuraEffect, AuraTarget)>,
    pub secret: Option<SecretTrigger>,
    pub divine_shield: bool,
    pub windfury: bool,
    pub charge: bool,
    pub spell_damage: i32,
    /// 不能主动攻击（如拉格纳罗斯）
    pub cant_attack: bool,
    /// 回合结束效果
    pub end_turn_effect: Option<CardEffect>,
}

// 宏：简化白板随从定义
macro_rules! vanilla {
    ($id:expr, $name:expr, $cost:expr, $atk:expr, $hp:expr) => {
        CardDef {
            id: $id,
            name: $name,
            card_type: CardType::Minion,
            cost: $cost,
            attack: $atk,
            health: $hp,
            durability: 0,
            battlecry: None,
            deathrattle: None,
            taunt: false,
            hero_power: None,
            aura: None,
            secret: None,
            divine_shield: false,
            windfury: false,
            charge: false,
            spell_damage: 0,
            cant_attack: false,
            end_turn_effect: None,
        }
    };
}

