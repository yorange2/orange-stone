//! M3-W2a cards (exp_tmw_w2a) — Across the Timeways sub-roadmap W2, first
//! split: the 118 non-legendary TIME_* collectible cards plus the two
//! legendaries implemented in this wave (TIME_038 Mister Clocksworth and
//! TIME_063 Timelord Nozdormu — they sit in the W2b set but their effects
//! are W2a shapes) — 120 cards in total, plus the 11 tokens they produce.
//!
//! Implementation decisions (per the M3-W2a spec, verified against
//! `cards/data/TIME_TRAVEL.json` and `/tmp/hs_full.json` 2026-08-09):
//! - **Rewind** (W1 machinery, `cards::rewind`): the 17 Rewind cards carry
//!   their own effects here — the replay is automatic via the play path.
//! - **Dormant** (FULL primitive, `core::component::Dormant`): while
//!   dormant a minion cannot attack, cannot be targeted (Stealth-like) and
//!   takes no damage; the countdown decrements at the owner's turn start
//!   and the component is removed at 0 (awaken). Cards: TIME_046 (3),
//!   TIME_063 (5), TIME_058's summoned 2-Cost (2), TIME_442's imprisoned
//!   minion (10,000). TIME_022 discounts while ANY minion is dormant.
//! - **Shred of Time** (TIME_025t): cast-when-drawn is simplified per the
//!   established precedent (EDR_445pt3 Emerald Portal, §14): the token is a
//!   playable 0-cost spell dealing 3 damage to your hero (§20). TIME_028 /
//!   TIME_029 "cast a Shred from your deck" scan the deck, remove the Shred
//!   and apply its own effect (§20).
//! - **Pool-open** (POOL_OPEN_CARDS registry): TIME_036 Royal Informant,
//!   TIME_039 Deja Vu, TIME_041 Futuristic Forefather, TIME_432 Intertwined
//!   Fate and TIME_876 Shapeshifter read the opponent's hand; TIME_041's
//!   guess is always right (§20).
//! - **Locations** (CardType::Location, the Core Set W8 representation):
//!   TIME_044 Past Gnomeregan, TIME_436 Past Conflux and TIME_810 Past
//!   Silvermoon carry their activation effects in the battlecry slot (the
//!   ActivateLocation path, like the CORE locations).
//! - **D2 random picks**: every targetable/choice pick that would be a
//!   player choice in the real game is a D2 random pick (the established
//!   convention) — TIME_016/212/218/431/447/602/770/860 and the location
//!   activations.
//! - **No-ops (§20)**: TIME_101 (Shatter trigger), TIME_214/217
//!   (would-damage interceptions), TIME_063's newest-expansion awakening
//!   check.
//! - **Stats**: TIME_856 Algeth'ar Instructor carries spell_damage 1 — the
//!   official JSON data (the card text says +2; the engine follows the
//!   data, §20).
//!
//! Fidelity rows: `docs/finished/fidelity-debt.md` §20 (+zh).

