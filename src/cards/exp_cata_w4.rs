//! M4-W4 cards (exp_cata_w4) — the Cataclysm sub-roadmap W4, the closing
//! wave: Deathwing, Worldbreaker (the C4 hero-replacement primitive) and
//! the remaining ~105 Cataclysm cards (2025–2026 expansions master
//! roadmap M4-W4, PR #159).
//!
//! Implementation decisions (per the M4-W4 spec, verified against
//! `/tmp/hs_full.json` and `cards/cards.json` 2026-08-09; the fidelity
//! rows are fidelity-debt.md §26, en + zh):
//! - **Deathwing's battlecry** is the `ChooseCataclysms` variant — the
//!   play path resolves the `ReplaceHero` primitive first (hardcoded for
//!   every `CardType::Hero`), then the def's battlecry; the four
//!   Cataclysms are data-defined 0-cost spells (`CATA_190t10..13`) whose
//!   `spell_effect` the ChoiceResolved handler resolves.
//! - **Herald cards carry no battlecry for the keyword** — the play paths
//!   call `cards::herald::resolve_herald`, keyed by the id (the W2 §24
//!   convention); CATA_497 Ultraxion's Cost reduction accumulates in the
//!   player's `deathwing_cost_reduction` (cost.rs).
//! - **The hand-transform trio** (CATA_551/552/553) transforms into their
//!   `t` tokens when a Dragon is played — the TurnStarted hook in
//!   trigger.rs; CATA_615 Genn's even/odd transform is the same hook.
//! - All other effects map to the M4-W4 CardEffect block (the names in
//!   this file are the authoritative card texts).

