//! M5-W2 cards (exp_jail_w2) — Escape from Violet Hold sub-roadmap W2,
//! the FINAL wave of the 2025–2026 expansions roadmap: all remaining
//! JAIL cards (10 legendaries + 108 non-legendaries) + the wave tokens
//! (2025–2026 expansions master roadmap M5-W2, PR #162).
//!
//! Implementation decisions (verified against `cards/cards.json` and the
//! full dump 2026-08-09; the fidelity rows are fidelity-debt.md §28,
//! en + zh):
//! - **The legendary shapes** (one per remaining legendary, F5-tested):
//!   Tiny Pal's ammunition rides `CardEffect::TinyPal { ammo }` +
//!   `ChoiceKind::TinyPalAmmo` (the battlecry pick) and the weapon
//!   `weapon_trigger` table re-surfaces the choice after each hero
//!   attack; Slice and Dice replays this-turn plays via the M3 Rewind
//!   machinery (`Player::rewind_turn_start_len`); King of the Underbelly
//!   and Staff of Trickery are D2-random discover pools with a
//!   `pending_discover_cost_reduction`; Warden Maiev's +3/+3-and-Dormant
//!   rides a `CardPlayed` per-card trigger; Murloc Holmes surfaces a
//!   `ChoiceKind::MurlocHolmes` read of the enemy hand and tracks the
//!   suspect for one turn (registered §28); Togwaggle merges both hands
//!   and splits them (`PlayerId` split convention, §28); R4T-C4TCH3R
//!   copies deck spells at battlecry and draws one at death; Zuramat's
//!   Prison is a location whose battlecry is a `ChooseHandCard`
//!   discard-summon, with the freed Zuramat (`JAIL_887t2`) playing one
//!   discarded card each turn (`Player::zuramat_discarded`).
//! - **The copy-family simplifications** (§28): Mind Sweeper and
//!   Enthralled Shade approximate "copied from the opponent" with the
//!   `CopiedFromOpponent` marker set in `copy_card_to_hand` when the
//!   source owner differs; Unshackle Soul's cost-1 rides `cost.rs`.
//! - **The counter cards** (§28): the three elemental spells track
//!   `Player::spells_cast_this_turn` (incremented in the `SpellCast`
//!   handler); the spell's own effect resolves BEFORE its `SpellCast`
//!   event, so a `>= 3` check means three OTHER spells; the tokens
//!   (JAIL_801t/803t/805t) reuse the parent spell's effect with a
//!   source-id branch inside the arm.
//! - **The "Casts When Drawn" cards** (JAIL_386t/879t/881t) follow the
//!   W1 Blight precedent: they are playable spells in this engine — the
//!   auto-cast-on-draw property is not modeled (§28).
//! - **Keyword riders**: Rush (JAIL_447, JAIL_459), Lifesteal
//!   (JAIL_454t, JAIL_805t) and the overload JAIL_452 => 2 ride the
//!   `apply_card_keywords` / overload tables; the 12 new Prepare cards
//!   register in `cards::prepare::is_prepare_card`.
//! - **Passive riders** ride per-card trigger attachments (mod.rs):
//!   Rioter (FriendlyMinionDamaged), Escape Artist (Attacked), Rat
//!   Burglar (TurnEnd), Tower of Ghouls (ThisMinionDamaged), Arachnathid
//!   (FriendlyMinionSummoned), Alarm-o-Matic (TurnStart), Black Market
//!   Auctioneer (FriendlySpellCast), Gallagio Goon / Black Market
//!   Overseer (CardPlayed), Maiev (CardPlayed), Spider Rider
//!   (HeroAttacked), Activated Golem (TurnEnd), Zuramat (TurnEnd),
//!   Irida (TurnStart).
//! - **Spiderling** rides the M4-W1 `AuraTarget::FriendlyHero` scope; the
//!   "on your turn" pin is dropped (§28). **Captive Nathrezim** rides the
//!   Mana Wraith cost aura (`IncreaseMinionCost`, both hands) (§28:
//!   "ALL" is approximated by the global bucket). **Scrappy Defender**'s
//!   conditional +5 Attack is dropped (§28).
//! - JAIL_440t Frail Ghoul is a self-defined token (the official card is
//!   HERO_11bpt; §28).

